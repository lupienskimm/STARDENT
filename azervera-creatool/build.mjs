// Joins src/*.js (in name order) into the single file creatool.js and copies it to the given targets.
// Usage: node tools/azervera-creatool/build.mjs [copy-to-path ...]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const files = fs.readdirSync(path.join(dir, "src")).filter((f) => f.endsWith(".js")).sort();
const sources = files.map((f) => `// ---- ${f} ----\n${fs.readFileSync(path.join(dir, "src", f), "utf8")}`);
const version = (sources.join("\n").match(/const VERSION = "([^"]+)"/) || [])[1] || "0.0.0";
const header = `/*!
 * Azervera CREATOOL ${version}: a visual editor you drop into any website.
 * made by lupienskim
 *
 * Texts, fonts, sizes, free moves, independent width and height with handles, shapes from corner points,
 * backgrounds, frosted glass, shadows, borders, corners, padding, magnetic guides, desktop/tablet/mobile views,
 * one page or the whole site, click actions and animations, requests described in words, draft/publish/backup,
 * comments, components, tokens, images, drawings from a library (added to the page or in place of an element),
 * a still region that stays put while the rest of an animation moves, a 3D snap-to-center lock, and a
 * client demo mode. Everything is stored as data in this browser and exported as one JSON for a coding agent. The
 * site's own elements are never removed from the DOM or moved (deleting one hides it): only text values, attributes and
 * inline styles change, and added drawings and texts live in one layer of their own, which keeps it safe on React, Next.js, Vue or plain HTML.
 * Settings: window.CreatoolConfig = {...} before the script (see README).
 */`;
const out = `${header}\n(() => {\n"use strict";\nif (typeof window === "undefined" || window.__creatool) return;\n\n${sources.join("\n")}\n})();\n`;
fs.writeFileSync(path.join(dir, "creatool.js"), out);
for (const target of process.argv.slice(2)) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(path.join(dir, "creatool.js"), target);
}
console.log(`creatool.js ${version}: ${files.length} parts, ${Math.round(out.length / 1024)} kB`);

// Stable scale: the TypeScript module for React and Next.js is made from the plain script, so both stay the same.
// meritko/v1 is Měřítko V1 and is frozen. Do not write into that folder.
// meritko/v2 is Měřítko V2. meritko/creatool-meritko.js is the same V2 script, so the demo keeps working.
const fit = fs.readFileSync(path.join(dir, "meritko", "creatool-meritko.js"), "utf8");
fs.writeFileSync(
  path.join(dir, "meritko", "creatool-meritko.ts"),
  `// Generated by build.mjs from creatool-meritko.js (edit that file). Stable scale for Azervera CREATOOL, made by lupienskim.
export type CreatoolFitConfig = { phone?: number; tablet?: number; desktop?: number; desktopFrom?: number; phoneMax?: number; short?: number; background?: string };

const SCRIPT = ${JSON.stringify(fit)};

/** Put the result first in <body> with dangerouslySetInnerHTML, so it runs before the first paint. */
export function creatoolMeritko(config?: CreatoolFitConfig) {
  return (config ? \`window.CreatoolFit=\${JSON.stringify(config)};\` : "") + SCRIPT;
}

/** The page zoom right now; divide getBoundingClientRect values by it before they go back into CSS. */
export function creatoolZoom() {
  if (typeof document === "undefined") return 1;
  return parseFloat(document.documentElement.style.zoom) || 1;
}
`,
);
console.log("meritko/creatool-meritko.ts written");
